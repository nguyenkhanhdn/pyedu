import { ALGORITHM_PROBLEMS } from "../../src/data/problemsData";

// These 60 exercises were added to the browser catalogue without database rows.
export const submissionCatalog = ALGORITHM_PROBLEMS.filter(p => /^(rn-|vl-)/.test(p.id));

export function catalogSql(): string {
  const quote = (value: unknown) => "'" + String(value).replaceAll("'", "''") + "'";
  const json = (value: unknown) => quote(JSON.stringify(value)) + "::jsonb";
  const array = (values: string[]) => `ARRAY[${values.map(quote).join(",")}]::text[]`;
  const rows = submissionCatalog.map(p => `(${[
    quote(p.id), quote(p.title), quote(p.level), quote(p.gradeGroup), quote(p.topic),
    quote(p.difficulty), array(p.tags || []), p.points, quote(p.timeLimit), quote(p.memoryLimit),
    quote(p.source || ""), quote(p.problemStatement), quote(p.inputFormat), quote(p.outputFormat),
    quote(p.constraints), json(p.sampleCases), quote(p.starterCode), array(p.hints || []),
    quote(p.solutionExplanation || ""), json(p.testCases),
  ].join(",")})`);
  return `-- Generated by npm run algo:submission-catalog. Existing exercises and submissions are preserved.\nINSERT INTO public.algorithm_problems\n(id,title,level,grade_group,topic,difficulty,tags,points,time_limit,memory_limit,source,problem_statement,input_format,output_format,constraints,sample_cases,starter_code,hints,solution_explanation,test_cases)\nVALUES\n${rows.join(",\n")}\nON CONFLICT (id) DO NOTHING;\n`;
}
